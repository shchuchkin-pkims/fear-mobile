package com.fear

/**
 * Имя участника звонка - по его метке сессии.
 *
 * В пакете приветствия звонка (HELLO2) едут первые 16 знаков метки, а не
 * имя, и это не недосмотр: HELLO2 аутентифицирован, но не зашифрован, и имя в
 * нём ретранслятор прочёл бы открытым текстом - ровно то, что Phase D убрала
 * из его журнала. Поэтому под плиткой видео раньше стояло «unMxhEaYN5s5…».
 *
 * Имя берётся там, где оно и так есть: в реестре клиента чата, куда оно
 * приходит подписанным анонсом личности внутри сквозного шифрования. На провод
 * оно не уходит, а вошедший посреди звонка получает имя, как только объявится.
 *
 * Окно звонка - отдельная активность без ссылки на клиент, поэтому
 * посредник - объект на весь процесс, как MessageNotifier и ThemeManager.
 */
object CallNames {
    /** Метка или её начало -> отображаемое имя; null - участник ещё не объявился. */
    @Volatile var resolver: ((String) -> String?)? = null

    /** Имя для подписи плитки; если неизвестно - сама метка, как раньше. */
    fun labelFor(tagOrPrefix: String): String =
        resolver?.invoke(tagOrPrefix)?.takeIf { it.isNotBlank() } ?: tagOrPrefix
}
