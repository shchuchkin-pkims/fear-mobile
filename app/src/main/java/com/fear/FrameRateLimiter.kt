package com.fear

/**
 * Частота кадров из настроек - предел, а не подсказка.
 *
 * Камера отдаёт кадры со своей частотой, обычно 30 в секунду, и раньше каждый
 * из них шёл в кодировщик и в сеть. Настройка «Frame rate» доходила только до
 * кодировщика как KEY_FRAME_RATE - подсказка для расчёта бит на кадр, а не
 * ограничение. На живом звонке телефон с настройкой 20 слал около 31 кадра в
 * секунду: на половину больше заказанного, каждый кадр - беднее, а приёмники
 * декодировали кадры, которые всё равно не успевали показать.
 *
 * Здесь лишние кадры отбрасываются до кодировщика: так экономится и сеть, и
 * батарея. Расписание держится по сетке, а не «не чаще, чем раз в N мс»: при
 * камере на 30 и пределе 20 проходит ровно два кадра из трёх, а не каждый
 * второй. После паузы - камера подвисла, приложение ушло в фон - сетка
 * начинается заново, а не наверстывает пропущенное залпом.
 *
 * Время приходит снаружи - класс проверяется JVM-тестами без устройства.
 */
class FrameRateLimiter(fps: Int) {

    companion object {
        /** Сколько раньше срока кадр всё ещё принимается: метки камеры дрожат. */
        const val JITTER_MS = 4.0
    }

    val fps: Int = fps.coerceIn(1, 120)
    private val intervalMs = 1000.0 / this.fps
    private var nextDueMs = Double.NaN

    /** Пропустить ли кадр, снятый в [nowMs]. */
    @Synchronized
    fun admit(nowMs: Long): Boolean {
        val now = nowMs.toDouble()
        if (nextDueMs.isNaN() || now - nextDueMs > intervalMs) {
            // Первый кадр или долгая пауза: начинаем сетку с этого кадра.
            nextDueMs = now + intervalMs
            return true
        }
        if (now + JITTER_MS < nextDueMs) return false
        nextDueMs += intervalMs
        return true
    }
}
